/**
 * Converts a Kinetic kebab-case icon ID into a valid Dart lowerCamelCase identifier.
 */
export function toDartIdentifier(id: string): string {
  const camel = toCamelCase(id);
  return DART_RESERVED_WORDS.has(camel) ? `${camel}Icon` : camel;
}

export interface GenerateFlutterDartOptions {
  /** Stroke width baked into the generated SVG strings. Defaults to 1.5. */
  stroke?: number;
  /** Corner radius baked into the generated SVG geometry. Defaults to 2.5. */
  radius?: number;
  /** Default stroke color baked into the SVG markup. Defaults to `currentColor`. */
  color?: string;
  /** Optional custom list of icons. Defaults to all 142 Kinetic icons. */
  icons?: IconDefinition[];
}

/**
 * Generates a complete, ready-to-paste `kinetic_icons.dart` file containing:
 * - `KineticIcons`: static const SVG strings for all icons + `all` lookup map
 * - `KineticIcon`: Flutter `StatelessWidget` powered by `flutter_svg`
 */
export function generateFlutterDart(
  options: GenerateFlutterDartOptions = {}
): string {
  const {
    stroke = DEFAULT_STROKE_WIDTH,
    radius = DEFAULT_CORNER_RADIUS,
    color = 'currentColor',
    icons = ICONS_CATALOG,
  } = options;

  const caps = getLineCaps(radius);

  const constEntries = icons.map((icon) => {
    const dartName = toDartIdentifier(icon.id);
    const inner = icon.draw(radius);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${stroke}" ${caps}>${inner}</svg>`;
    return `  /// Kinetic icon: \`${icon.id}\` (${icon.category})\n  static const String ${dartName} = r'''${svg}''';`;
  });

  const mapEntries = icons.map((icon) => {
    const dartName = toDartIdentifier(icon.id);
    return `    '${icon.id}': ${dartName},`;
  });

  return `// GENERATED BY KINETIC ICONS STUDIO — DO NOT EDIT BY HAND
// Icons: ${icons.length} | Stroke: ${stroke.toFixed(2)}px | Corner Radius: ${radius.toFixed(2)}px
//
// Requires \`flutter_svg\` in your pubspec.yaml:
//   dependencies:
//     flutter_svg: ^2.0.10
//
// Usage:
//   KineticIcon(KineticIcons.home)
//   KineticIcon(KineticIcons.shieldCheck, size: 28, color: Colors.indigo)

import 'package:flutter/widgets.dart';
import 'package:flutter_svg/flutter_svg.dart';

/// Parametric SVG strings for all ${icons.length} Kinetic icons.
class KineticIcons {
  KineticIcons._();

${constEntries.join('\n\n')}

  /// Lookup map of all Kinetic icons keyed by kebab-case icon ID.
  static const Map<String, String> all = <String, String>{
${mapEntries.join('\n')}
  };
}

/// Renders a Kinetic SVG icon using \`flutter_svg\`.
///
/// Example:
/// \`\`\`dart
/// KineticIcon(KineticIcons.home)
/// KineticIcon(KineticIcons.aiSpark, size: 32, color: const Color(0xFF2563EB))
/// \`\`\`
class KineticIcon extends StatelessWidget {
  const KineticIcon(
    this.svg, {
    super.key,
    this.size = 24.0,
    this.color,
    this.semanticsLabel,
  });

  /// Raw SVG string from [KineticIcons], e.g. \`KineticIcons.home\`.
  final String svg;

  /// Width and height of the icon in logical pixels. Defaults to \`24.0\`.
  final double size;

  /// Optional tint color. Falls back to the nearest [IconTheme] color.
  final Color? color;

  /// Optional accessibility label for screen readers.
  final String? semanticsLabel;

  @override
  Widget build(BuildContext context) {
    final Color effectiveColor =
        color ?? IconTheme.of(context).color ?? const Color(0xFF111113);

    return SvgPicture.string(
      svg,
      width: size,
      height: size,
      colorFilter: ColorFilter.mode(effectiveColor, BlendMode.srcIn),
      semanticsLabel: semanticsLabel,
    );
  }
}
`;
}
